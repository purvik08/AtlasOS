#!/usr/bin/env bash
# AtlasOS Yocto Environment Setup — Raspberry Pi 5 ARM64
#
# Run this script from the directory where you want to place the Yocto build.
# Target: Raspberry Pi 5 / aarch64 / Yocto Scarthgap (5.0 LTS)
#
# Usage:
#   chmod +x scripts/yocto/setup-rpi5.sh
#   ./scripts/yocto/setup-rpi5.sh
#
# Requirements (host):
#   Ubuntu 22.04 or 24.04 (recommended)
#   16 GB+ RAM, 100 GB+ disk
#   Python 3.8+, git, repo, kas (optional)

set -euo pipefail

ATLAS_BUILD_DIR="${ATLAS_BUILD_DIR:-${PWD}/atlas-yocto-build}"
YOCTO_BRANCH="scarthgap"
RPI_LAYER_BRANCH="scarthgap"

echo "=== AtlasOS Yocto Setup for Raspberry Pi 5 ARM64 ==="
echo "Build directory: ${ATLAS_BUILD_DIR}"
echo ""

# Install host dependencies (Ubuntu/Debian)
if command -v apt-get &>/dev/null; then
    echo "[1/5] Installing host dependencies..."
    sudo apt-get update -qq
    sudo apt-get install -y --no-install-recommends \
        gawk wget git diffstat unzip texinfo gcc build-essential \
        chrpath socat cpio python3 python3-pip python3-pexpect \
        xz-utils debianutils iputils-ping python3-git python3-jinja2 \
        libegl1-mesa libsdl1.2-dev xterm python3-subunit mesa-common-dev \
        zstd liblz4-tool file locales libacl1
    sudo locale-gen en_US.UTF-8
fi

mkdir -p "${ATLAS_BUILD_DIR}"
cd "${ATLAS_BUILD_DIR}"

# Clone Poky
if [ ! -d "poky" ]; then
    echo "[2/5] Cloning Poky (${YOCTO_BRANCH})..."
    git clone --depth 1 --branch "${YOCTO_BRANCH}" \
        https://git.yoctoproject.org/poky.git poky
else
    echo "[2/5] Poky already cloned, skipping."
fi

# Clone meta-raspberrypi
if [ ! -d "meta-raspberrypi" ]; then
    echo "[3/5] Cloning meta-raspberrypi (${RPI_LAYER_BRANCH})..."
    git clone --depth 1 --branch "${RPI_LAYER_BRANCH}" \
        https://git.yoctoproject.org/meta-raspberrypi meta-raspberrypi
else
    echo "[3/5] meta-raspberrypi already cloned, skipping."
fi

# Clone meta-openembedded
if [ ! -d "meta-openembedded" ]; then
    echo "[4/5] Cloning meta-openembedded (${YOCTO_BRANCH})..."
    git clone --depth 1 --branch "${YOCTO_BRANCH}" \
        https://github.com/openembedded/meta-openembedded.git meta-openembedded
else
    echo "[4/5] meta-openembedded already cloned, skipping."
fi

# Initialise build environment
echo "[5/5] Initialising Yocto build environment..."
# shellcheck source=/dev/null
source poky/oe-init-build-env build-rpi5

# Write local.conf for Raspberry Pi 5 ARM64
cat > conf/local.conf << 'EOF'
# AtlasOS — Raspberry Pi 5 ARM64 build configuration
# Generated by scripts/yocto/setup-rpi5.sh
# Yocto: scarthgap (5.0 LTS)

MACHINE = "raspberrypi5"
DEFAULTTUNE = "cortexa76"

# 64-bit ONLY — no 32-bit compat
MULTILIB_VARIANTS = ""

# NetworkManager as primary network backend
DISTRO_FEATURES:append = " wifi networkmanager bluez5"
CORE_IMAGE_EXTRA_INSTALL += "networkmanager networkmanager-nmtui"

# systemd
DISTRO_FEATURES:append = " systemd"
DISTRO_FEATURES:remove = " sysvinit"
VIRTUAL-RUNTIME_init_manager = "systemd"
VIRTUAL-RUNTIME_initscripts = "systemd-compat-units"

# Audio: PipeWire
CORE_IMAGE_EXTRA_INSTALL += "pipewire pipewire-alsa wireplumber alsa-utils"

# Python 3.12
IMAGE_INSTALL:append = " python3 python3-pip"

# Enable UART for debugging
ENABLE_UART = "1"

# Build performance
BB_NUMBER_THREADS ?= "$(nproc)"
PARALLEL_MAKE ?= "-j $(nproc)"

# Use tmpfs for tmp/ (faster builds)
# TMPDIR = "/tmp/yocto-tmp"

# SDK toolchain target
SDKMACHINE = "x86_64"
EOF

echo ""
echo "=== Setup complete ==="
echo ""
echo "Next steps:"
echo "  1. Add meta-atlas layer to bblayers.conf"
echo "  2. Run: bitbake atlas-image"
echo "  3. Flash: sudo dd if=tmp/deploy/images/raspberrypi5/atlas-image-raspberrypi5.wic of=/dev/sdX bs=4M status=progress"
echo ""
echo "See docs/yocto/raspberrypi5-arm64.md for full documentation."
